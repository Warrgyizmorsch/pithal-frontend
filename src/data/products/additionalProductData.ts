function toApplicationItems(items: string[]) {
  const iconMap: Record<string, string> = {
    Mining: "basket",
    Aggregates: "mountain",
    Construction: "building",
    Cement: "factory",
    Recycling: "recycle",
    Infrastructure: "hardHat",
  };

  return items.map((label) => ({ label, icon: iconMap[label] ?? "factory" }));
}

